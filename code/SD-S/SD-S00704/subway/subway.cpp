#include <bits/stdc++.h>
using namespace std;
long long c, n, m, d, q, w[500005], k[505], a[505][20005], t[505][20005];
int main() {
	freopen("subway.in", "r", stdin);
	freopen("subway.out", "w", stdout);
	ios::sync_with_stdio(false);
	cin.tie(0);
	cin >> c >> n >> m >> d >> q;
	for(int i = 0; i < m; i++) {
		cin >> w[i];
	}
	for(int i = 0; i < n; i++) {
		cin >> k[i];
		for(int j = 0; j < k[i]; j++) {
			cin >> a[i][j] >> t[i][j]; 
		}
	}
	long long x, y;
	for(int i = 0; i < q; i++) {
		cin >> x >> y;
		long long s = w[x] + w[y] + t[x][x] + t[x][x + 1];
		cout << s << endl;
	}
	return 0;
}
