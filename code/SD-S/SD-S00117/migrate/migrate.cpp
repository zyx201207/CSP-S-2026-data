#include <bits/stdc++.h>
#define N 2000010
#define M 21
#define int long long 
using namespace std;
int c, t, n, d, x[N];
int pr[N], dp[N], cnt[N], s[N], r[N];
signed main() {
	freopen("migrate.in", "r", stdin);
	freopen("migrate.out", "w", stdout);
	cin.tie(0) -> sync_with_stdio(0);
	cin >> c >> t;
	while(t--) {
		cin >> n >> d;
		for(int i = 1; i <= n; i++) cin >> x[i];
		int l = 1;
		for(int i = 1; i <= n; i++) {
			while(x[i] - x[l] > d) l++;
			if(l == i) pr[i] = -1;
			else pr[i] = l;
		}
		int ans = 0;
		for(int i = 1; i <= n; i++) {
			dp[i] = 0; cnt[i] = s[i] = 1; s[i - 1] = 0;
			r[0] = i;
			for(int j = i + 1; j <= n; j++) {
				if(pr[j] == -1) break;
				int f = max(pr[j], i);
//				if(i == 2 && j == 5) cout << "debug: " << f << ' ' << r[dp[f]] << '\n';
				dp[j] = dp[f] + 1;
				cnt[j] = s[r[dp[f]]] - s[f - 1];
				r[dp[j]] = j;
				s[j] = s[j - 1] + cnt[j];
//				if(i == 2 && j == 5) cout << "debug: " << dp[j] << ' ' << cnt[j] << '\n';
				if(cnt[j] == 2) {
//					cout << i << ' ' << j << '\n';
					ans++;
				}
			}
		}
		cout << ans << '\n';
	}
	return 0;
}
