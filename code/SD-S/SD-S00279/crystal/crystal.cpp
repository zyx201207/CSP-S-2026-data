#include <bits/stdc++.h>

using namespace std;
long long n,m,a[500010],ans=1;
int main()
{
	freopen("crystal.in","r",stdin);
	freopen("crystal.out","w",stdout);
	cin>>n>>m;
	for (int i=1;i<=n;i++){
		cin>>a[i];
	}
	if(n<=5000){
		sort(a+1,a+n+1);
		for (int i=2;i<=n;i++){
			int t=m,s;
			for (int j=i;j>=1;j--){
				if(a[i]-a[j]<=t){
					t-=a[i]-a[j];
				}
				else{
					s=j;
					break;
				}
			}
			if(i-s>ans){
				ans=i-s;
			}
		}
		cout<<ans;
	}
	else{
		bool p=true,pp=true,ppp=true;
		long long mm=1e13,mx=-1e13;
		for (int i=1;i<=n;i++){
			if(a[i]>100){
				p=false;
			}
			if(a[i]!=i){
				pp=false;
			}
			mm=min(mm,a[i]);
			mx=max(mx,a[i]);
		}
		for (int i=2;i<=n;i++){
			if(a[i]-a[i-1]!=a[2]-a[1]){
				ppp=false;
			}
		}
		if(p){
			for (int i=mm;i<=mx;i++){
				long long z=0,t=m;
				for (int j=1;j<=n;j++){
					if(a[j]<i&&i-a[j]<=t){
						t-=(i-a[j]);
						z++;
					}
					else{
						break;
					}
				}
				if(z>ans){
					ans=z;
				}
			}
			cout<<ans;
		}
		else if(pp){
			long long t=m,cnt=1;
			for (int i=1;i<=n;i++){
				m-=i;
				if(m<0){
					break;
				}
				cnt++;
			}
			if(cnt>n){
				cnt=n;
			}
			cout<<cnt;
		}
		else if(ppp){
			long long t=m,cnt=1;
			for (int i=1;i<=n;i++){
				m-=i*(a[2]-a[1]);
				if(m<0){
					break;
				}
				cnt++;
			}
			if(cnt>n){
				cnt=n;
			}
			cout<<cnt;
		}
	}
	return 0;
}
