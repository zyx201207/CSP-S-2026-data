#include <iostream>
using namespace std;
int main()
{
    freopen("card.in", "r", stdin);
    freopen("card.out", "w", stdout);
    int n,m;
    long long a[n] = {};
    for (int i = 1; i <= n; i++){
        a[n].ap(m);
        if(a[n] = i){
            a[n].pop();
        }
    }
    cout << a[n];
    fclose(stdin);
    fclose(stdout);
    return 0;
}
