#include <bits/stdc++.h>
#include <iostream>
#include <cmath>
#include <algorithm>
#include <vector>
using namespace std;
int c,n,m,d,q;
int w[500005],k[505];
int x,y;
long long ans;
bool ff=false;
struct lx{
	int y,j;
	int yt,jt;
}sub[500005];
struct zt{
	vector<int> o;
	bool f;
}st[505];
void bfs(int l,int r,long long t){
	if(l==r){
		if(ff==true) ans=min(ans,t);
		else{
			ans=t;
			ff=true;
//			cout<<"*"<<endl;
		}
	}
	else{
		for(int i=0;i<st[l].o.size();i++){
//			cout<<")"<<st[l].o.size()<<endl;
			if(st[sub[st[l].o[i]].j].f==false){
				st[sub[st[l].o[i]].j].f=true;
				bfs(sub[st[l].o[i]].j,r,t+sub[st[l].o[i]].yt+sub[st[l].o[i]].jt);
				st[sub[st[l].o[i]].j].f=true;
			}
		}
	}
	return;
} 
int main(){
	freopen("subway.in","r",stdin);
//	freopen("subway.out","w",stdout);
	cin>>c>>n>>m>>d>>q;
	for(int i=0;i<m;i++){
		cin>>w[i];
//		cout<<w[i]<<" ";
	}
//	cout<<endl;
	if((c>=7 && c<=11) || c==0){
		for(int i=0;i<n;i++){
			cin>>k[i];
			cin>>sub[i].y>>sub[i].yt>>sub[i].j>>sub[i].jt;
			sub[i+n+1].y=sub[i].j;
			sub[i+n+1].yt=sub[i].jt;
			sub[i+n+1].j=sub[i].y;
			sub[i+n+1].jt=sub[i].yt;
			st[sub[i].y].o.push_back(i);
			st[sub[i].j].o.push_back(i+n+1);
		}
		for(int u=0;u<10;u++){
			cin>>x>>y;
			ans=0;
			ff=false;
			for(int i=0;i<m;i++){
				st[i].f=false;
			}
			st[x].f=true;
			bfs(x,y,w[x]+w[y]);
			cout<<ans<<endl;
		}
	}
	return 0;
}
