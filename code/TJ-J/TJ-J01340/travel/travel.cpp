#include<bits/stdc++.h>
using namespace std;
int main()
{
	freopen("traval.in","r",stdin);
	freopen("traval.out","w",stdout);
	int c1, c2;
	string s1, s2;
//	c1,s1,c2,s2分别表示小R的车票上的车厢号、座位号，以及小X的车票上的车厢号、座位号。
	cin>>c1>>s1>>c2>>s2;
//	两张车票对应的座位是否在同一节车厢
	if(c1==c2)
		cout<<1;
	else
	{
		cout<<"0000";
		return 0;
	}
//	两张车票对应的座位是否在同一节车厢的同一排
	if((((s1[0]-'0')*10)+(s1[1]-'0'))==(((s2[0]-'0')*10)+(s2[1]-'0')))
		cout<<1;
	else
	{
		cout<<"000";
		return 0;
	}
//	两张车票对应的座位是否在同一节车厢的同一排，且位于过道的同一侧
	if(((s1[2]=='A')&&(s2[2]=='B'))||((s1[2]=='B')&&(s2[2]=='A'))||((s1[2]=='B')&&(s2[2]=='C'))||((s1[2]=='D')&&(s2[2]=='F'))||((s1[2]=='F')&&(s2[2]=='D'))||((s1[2]=='A')&&(s2[2]=='C'))||((s1[2]=='C')&&(s2[2]=='A'))||((s1[2]=='C')&&(s2[2]=='B')))
		cout<<1;
	else
	{
		cout<<"00";
		return 0;
	}
//	两张车票对应的座位是否相邻
	if(((s1[2]=='A')&&(s2[2]=='B'))||((s1[2]=='B')&&(s2[2]=='A'))||((s1[2]=='B')&&(s2[2]=='C'))||((s1[2]=='D')&&(s2[2]=='F'))||((s1[2]=='F')&&(s2[2]=='D'))||((s1[2]=='C')&&(s2[2]=='B')))
		cout<<1;
	else
		cout<<0;
	return 0;
}
