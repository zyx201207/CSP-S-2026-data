#include<bits/stdc++.h>

using namespace std;

#define int long long
int n,m,a[500010];

int nowNeed,las,maxer;

signed main(){
	freopen("crystal.in" ,"r",stdin );
	freopen("crystal.out","w",stdout);
	cin>>n>>m;
	
	for(int i=1;i<=n;i++){
		cin>>a[i];
	}
	sort(a+1,a+1+n);
	las=1;
	for(int i=2;i<=n;i++){
		nowNeed+=(i-las)*(a[i]-a[i-1]);
		while(nowNeed>m){
			las++;
			nowNeed-=a[i]-a[las-1];
		}
		maxer=max(maxer,i-las+1);
	}
	cout<<maxer<<endl;
	return  0;
}


