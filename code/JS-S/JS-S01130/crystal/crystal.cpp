
#include<bits/stdc++.h>
using namespace std;
long long a[500005],n,m,ans;
int main(){
    freopen("crystal.in","r",stdin);
    freopen("crystal.out","w",stdout);
    cin>>n>>m;
    for(int i=1;i<=n;i++) cin>>a[i];
    sort(a+1,a+1+n);
    for(int i=1;i<=n;i++){
        for(int j=i;j<=n;j++){
            int sum=0;
            for(int k=i;k<=j;k++) sum+=(a[j]-a[k]);
            if(sum<=m)ans=max(ans,(long long)j-i+1);
        }
    }
    cout<<ans;

























































































































































































































































































return 0;



















































































}
