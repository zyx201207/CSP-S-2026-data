#include<bits/stdc++.h>
using namespace std;
typedef long long ll;
const int N = 2e6+5;
int c,T;
ll n,a[N],d,ans;
void solve(){
    cin >> n >> d;ans = 0;
    for(int i = 1;i <= n;i++) cin >> a[i];
    for(int l = 1;l <= n;l++){
        for(int r = l+1;r <= n;r++){
            if(a[r]-a[l] <= d) continue;
            int cnt = 0;
            for(int i = l+1;i < r;i++){
                if(a[i]-a[l] <= d && a[r]-a[i] <= d) cnt++;
            }
            if(cnt == 2) ans++;
        }
    }
    cout << ans << "\n";
}
int main(){
    freopen("migrate.in","r",stdin);
    freopen("migrate.out","w",stdout);
    cin >> c >> T;
    while(T--) solve();
    return 0;
}
