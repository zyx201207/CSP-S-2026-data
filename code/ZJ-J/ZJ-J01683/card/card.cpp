#include<bits/stdc++.h>
using namespace std;
int n,m,l;
int a[500010],k[500010],cnt[300010],dp[300010];
int main(){
	freopen("card.in","r",stdin);
	freopen("card.out","w",stdout);
	scanf("%d %d",&n,&m);
	for(int i=1;i<=n;i++){
		scanf("%d",&a[i]);
	}
	for(int i=1;i<=n;i++){
		cout<<"no."<<i<<endl;
		l=0;
		memset(dp,0,sizeof dp);
		for(int j=i;j<=n;j++){
			if(dp[a[j]]==0){
				l++;
				k[l]=a[j];
				dp[a[j]]=l;
			}
			else{
				int q=dp[a[j]];
				for(int t=dp[a[j]]+1;t<=l;t++){
					k[t]=0;
					dp[t]=0;
				}
				l=q;
				k[l]=a[j];
			}
		}
		for(int j=1;j<=l;j++){
			cnt[k[j]]++;
		}
	}
	for(int i=1;i<=m;i++){
		printf("%d ",cnt[i]);
	}
	return 0;
}



































































































































































































































































































































































































































































































