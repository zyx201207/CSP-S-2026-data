#include <bits/stdc++.h>
using namespace std;
const int maxn = 2e6+100;
long long dis[maxn];
long long a[maxn],vis[maxn];
vector<long long>g[maxn];
int ans = 0,z = 0;
void dfs(long long cur,long long fa,long long st){
	int siz = g[cur].size();
	if(!dis[cur])dis[cur] = st;
	for(int i = 0;i<siz;i++){
		int nxt = g[cur][i];
		if(nxt == fa)continue;
		if(st+1 == dis[nxt]){
			vis[nxt]++;
		}
		dfs(nxt,cur,st+1);
	}
	return ;
}
int main(){
	freopen("migrate.in","r",stdin);
	freopen("migrate.out","w",stdout);
	ios::sync_with_stdio(0);
	cin.tie(0);
	cout.tie(0);
	long long c,t;
	cin>>c>>t;
	while(t--){
		long long n,d;
		cin>>n>>d;
		for(int i = 1;i<=n;i++)cin>>a[i],g[i].clear();
		for(int i = 1;i<=n;i++){
			for(int j = n;j>i;j--){
				if(a[j]<=d+a[i]){
					g[i].push_back(j);
				}
			}
		}
		ans = 0;
		for(int i = 1;i<=n;i++){
			memset(dis,0,sizeof(dis));
			memset(vis,0,sizeof(vis));
			dfs(i,0,0);
			for(int j = 1;j<=n;j++)ans+=(vis[j] == 1);
		}
		cout<<ans<<'\n';
	}
	return 0;
}
