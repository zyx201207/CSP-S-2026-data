#include<bits/stdc++.h>
#define int long long
using namespace std;
const int N=5e5+5;
int n,m,ans;
int a[N];
signed main()
{
	freopen("crystal.in","r",stdin);
	freopen("crystal.out","w",stdout);
	scanf("%lld %lld",&n,&m);
	for(int i=1;i<=n;++i)
		scanf("%lld",&a[i]);
	sort(a+1,a+n+1);
	int l=1,sum=0,la=a[1];
	for(int r=1;r<=n;++r)
	{
		sum+=(r-l)*(a[r]-la);
		while(sum>m)
		{
			++l;
			sum-=a[r]-a[l];
		}
		ans=max(ans,r-l+1);
		la=a[r];
	}
	printf("%lld",ans);
	return 0;
}
