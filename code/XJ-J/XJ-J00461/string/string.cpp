#include<bits/stdc++.h>
using namespace std;
long long a[200005];
char c[200005];
int main(){
	freopen("string.in","r",stdin);
	freopen("string.out","w",stdout);
	long long n,i,j,num,ans=0;
	cin>>n;
	for(i=1;i<=n;i++)
	{
		cin>>a[i]>>c[i];
	}
	if(a[1]>a[n])
	{
		i=1;
		j=n;
		while(i<j)
		{
			num=a[i];
			while(num)
			{
				if(i>=j)
				{
					break;
				}
				if(num<a[j])
				{
					if(c[i]==c[j])
					{
						a[j]-=num;
						num=0;
					}
					else
					{
						ans+=num;
						a[j]-=num;
						num=0;
					}
				}
				else if(c[i]!=c[j])
				{
					ans+=a[j];
					num-=a[j];
				}
				else
				{
					num-=a[j];
				}
				j--;
			}
			j++;
			i++;
		}
	}
	else
	{
		i=n;
		j=1;
		while(i>j)
		{
			num=a[i];
			while(num)
			{
				if(i<=j)
				{
					break;
				}
				if(num<a[j])
				{
					if(c[i]==c[j])
					{
						a[j]-=num;
						num=0;
					}
					else
					{
						ans+=num;
						a[j]-=num;
						num=0;
					}
				}
				else if(c[i]!=c[j])
				{
					ans+=a[j];
					num-=a[j];
				}
				else
				{
					num-=a[j];
				}
				j++;
			}
			j--;
			i--;
		}
	}
	cout<<ans;
	return 0;
}
