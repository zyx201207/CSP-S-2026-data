#include<bits/stdc++.h>
using namespace std;
string c1,c2,s1,s2;
int main()
{

	cin>>c1;
	cin>>s1;
	cin>>c2;
	cin>>s2;
	if(c1==c2)
	{
		printf("1");
		if(s1[1]==s2[1]&&s1[2]==s2[2])
		{
			printf("1");
			if((s1[3]=='D'&&s2[3]=='F')||(s2[3]=='D'&&s1[3]=='F'))
			{
				printf("11");
			}
			else
			{
				if(s1[3]=='D'||s2[3]=='F'||s2[3]=='D'||s1[3]=='F')
				{
					printf("00");
				}
				else
				{
					printf("1");
					if((s1[3]=='C'&&s2[3]=='A')||(s1[3]=='A'&&s2[3]=='C'))
					{
						printf("0");
					}
					else
					{
						printf("1");
					}
				}
			}
		}
		else
		{
			printf("000");
		}
	}
	else
	{
		printf("0000");
	}
}
