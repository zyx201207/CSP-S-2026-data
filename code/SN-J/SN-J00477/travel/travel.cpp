#include<bits/stdc++.h>
using namespace std;

string c1, c2, s1, s2, ans;

int main(){
	freopen("travel.in", "r", stdin);
	freopen("travel.out", "w", stdout);
	ios::sync_with_stdio(false);
	cin.tie(0);
	cout.tie(0);
	cin >> c1 >> s1 >> c2 >> s2;
	if(c1 == c2){
		ans += "1";
		if(s1[0] == s2[0] && s1[1] == s2[1]){
			ans += "1";
			char a = s1[2];
			char b = s2[2];
			if(!(((a == 'A' || a == 'B' || a == 'C') && (b == 'D' || b == 'F')) || ((a == 'D' || a == 'F') && (b == 'A' || b == 'B' || b == 'C')))){
				ans += "1";
				if((a == 'A' && b == 'B') || (a == 'B' && b == 'C') || (a == 'B' && b == 'A') || (a == 'C' && b == 'B') || (a == 'D' && b == 'F') || (a == 'F' && b == 'D')){
					ans += "1";
				}else{
					ans += "0";
				}
			}else{
				ans += "00";
			}
		}else{
			ans += "000";
		}
	}else{
		ans += "0000";
	}
	cout << ans << "\n";
	return 0;
}
