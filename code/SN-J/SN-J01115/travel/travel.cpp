#include<bits/stdc++.h>
using namespace std;
string c1,s1,c2,s2,a;
int main()
{
	cin>>c1>>s1>>c2>>s2;
	if(c1==c2)
	{
		a[0]='1';
		if(s1[0]==s2[0])
	    {
		    if(s1[1]==s2[1])
		    {
			    a[1]='1';
			    if(s1[2]-s2[2]==2||s1[2]-s2[2]==-2)
		 	    {
		            if(s1[2]=='A'||s1[2]=='C')
		            {
			            if(s2[2]=='A'||s2[2]=='C')
			            {
				            a[2]='1';
				            a[3]='0';
			            }
			            else
			            {
			    	        a[2]='0';
			    	        a[3]='0';
			            }
			        }
			        else
			        {
				        a[2]='0';
				        a[3]='0';
			        }
		        }
			    if(s1[2]-s2[2]==1||s1[2]-s2[2]==-1)
	            {
		            if(s1[2]=='C'||s1[2]=='D')
		            {
			            if(s2[2]=='C'||s2[2]=='D')
			            {
				            a[2]='0';
				            a[3]='0';
			            }
			            else
			            {
				            a[2]='1';
				            a[3]='1';
			            }
		            }    
		            else
		            {
			            a[2]='1';
			            a[3]='1';
		            }
	            }
            }
		    else
		    {
			    a[1]='0';
			    a[2]='0';
			    a[3]='0';
		    }
	    }
	    else
	    {
		    a[2]='0';
	        a[3]='0';
	    }
	}
	else
	{
	    a[0]='0';
	    a[1]='0';
	    a[2]='0';
	    a[3]='0';
    }
    for(int i=0;i<4;i++)
	{
		cout<<a[i];
	}
	return 0;
}
