#include<bits/stdc++.h>
using namespace std;
#define int long long
int a[500005],num[300005],ans[300005],r;
bool vis[300005];
vector<int> c[300005];
void dfs(int x){
	ans[x]+=num[x];
	for(auto v:c[x]){
		dfs(v);
		ans[x]+=ans[v];
	}
	return;
}
signed main(){
	ios::sync_with_stdio(0);
	cin.tie(0),cout.tie(0);
	freopen("card.in","r",stdin);
	freopen("card.out","w",stdout);
	int n,m;
	cin>>n>>m;
	for(int i=1;i<=n;i++) cin>>a[i],num[a[i]]++;
	r=a[n],vis[r]=1;
	for(int i=n-1;i>=1;i--){
		if(!vis[a[i]]){
			c[a[i+1]].push_back(a[i]);
			vis[a[i]]=1;
		}
	}
	dfs(r);
	for(int i=1;i<=m;i++) cout<<ans[i]<<' ';
	return 0;
}

