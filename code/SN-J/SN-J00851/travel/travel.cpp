#include<bits/stdc++.h>
using namespace std;

int main(){
	int c1,c2;
	char s1[4],s2[4];
	cin>>c1>>s1[0]>>s1[1]>>s1[2]>>c2>>s2[0]>>s2[1]>>s2[2];
	//cout<<c1<<" "<<s1[0]<<s1[1]<<s1[2]<<" "<<c2<<" "<<s2[0]<<s2[1]<<s2[2];
	if(c1!=c2) cout<<"0000";
	else if(c1==c2 && s1[1]!=s2[1]) cout<<"1000";	
	else if(c1==c2 && s1[1]==s2[2] && (((s1[2]>='A' && s1[2]<='C') && (s2[2]>='A' && s2[2]<='C')) || ((s1[2]>='D' && s1[2]<='F') && (s2[2]>='D' && s2[2]<='F')))) cout<<"1110";
	else if(c1==c2 && s1[1]==s2[2] && (((s1[2]>='A' && s1[2]<='C') && (s2[2]>='A' && s2[2]<='C')) || ((s1[2]>='D' && s1[2]<='F') && (s2[2]>='D' && s2[2]<='F'))) && (s1[2]++==s2[2] || s1[2]--==s2[2])) cout<<"1111";
	else cout<<"1100";
	return 0;
}
