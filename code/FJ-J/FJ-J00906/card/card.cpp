int main(){
	freopen("card.in","r",stdin);
	freopen("card.out","w",stdout);
	cin>>n>>m;
	for(int i=1;i<=n;i++){
		cin>>a[i];
		d[i]=a[i]-a[i-1];
	}
	for(int i=1;i<=n;i++){
		if(i==n){
			ans[a[i]]++;
			break;
		}
		for(int j=n;j>=i;j--){
			if(f[a[j]])continue;
			f[a[j]]=1;
			for(int k=i;k<j;k++){
				if(a[k]==a[j]){
					d[k-1]-=114514;
					d[j]+=114514;
				}
			}
		}
		for(int j=i;j<=n;j++){
			b[j]=b[j-1]+d[j];
			if(b[j]>0&&f[b[j]]){
				ans[a[j]]++;
			}
			f[b[j]]=0;
			d[j]=a[j]-a[j-1];
		}
		for(int j=1;j<=m;j++)f[j]=0;
	}
	for(int i=1;i<=m;i++){
		cout<<ans[i]<<" ";
	}
	cout<<'\n';
	return 0;
}
