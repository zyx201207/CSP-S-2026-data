#include<bits/stdc++.h>
#include<iostream>
using namespace std;
int n,p=0;
string a="";
int main(){
	freopen("string.in","r",stdin);
	freopen("string.out","w",stdout);
	cin>>n;
	for(int i=0;i<n;i++){
		long long x;
		string a1;
		cin>>x>>a1;
		for(int j=0;j<x;j++){
			a+=a1;
		}
	}
	n=a.size();
	if(a.size()%2==0){
		for(int i=0;i<n/2;i++){
			if(a[i]!=a[n-1-i]){
				p++;
			}
		}
	}
	else{
		for(int i=0;i<(n-1)/2;i++){
			if(a[i]!=a[n-1-i]){
				p++;
			}
		}
	}
	cout<<p;
	return 0;
}
