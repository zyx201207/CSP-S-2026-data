#include<bits/stdc++.h>
using namespace std;
#define int long long
int a[500010],r[300010];
int s[500010],t=1;
signed main(){
	freopen("card.in","r",stdin);
	freopen("card.out","w",stdout);
	int n,m;
	cin>>n>>m;
	for(int i=1;i<=n;i++){
		cin>>a[i];
	}
	for(int i=1;i<=n;i++){
		for(int j=i;j<=n;j++){
			for(int k=1;k<=t;k++){
				if(s[k]==a[j]){
					t=k-1;
				}
			}
		}
		for(int j=1;j<=t;j++){
			r[s[j]]++;
		}
	}
	for(int i=1;i<=m;i++){
		cout<<r[i]<<' ';
	}
	cout<<endl;
	return 0;
}
