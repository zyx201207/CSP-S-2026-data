#include<bits/stdc++.h>
using namespace std;
int main(){
	freopen("crystal.in","r",stdin);
	int n,m,b,h,j,k;
	char a[b];
	cin >> n >> m >> b;
	for(int i; i<=m; i++){
		n+1;
		h=n;
		for(int o; o<=n; o++){
			b+2;
			j=b;
			for(int r; r<=b; r++){
				a[b]++;
				a[b]=k;
				break;
			}
		}
	}
	cout << n << b << k;
	freopen("crystal.out","w",stdout);
	return 0;
}
