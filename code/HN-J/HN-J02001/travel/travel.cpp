#include<bits/stdc++.h>
using namespace std;


int main()
{
freopen("travel.in","r",stdin);
freopen("travel.out","w",stdout);
	char s1[3],s2[3],t1[2],t2[2];
	scanf("%s%s%s%s",t1,s1,t2,s2);
	int w1=false,w2=false,w3=false,w4=false;
	if(t1[0]==t2[0] && t1[1]==t2[1])
	{
		w1=1;
		if(s1[1]==s2[1] && s1[0]==s2[0])
		{
			w2=1;
			if((s1[2]<='C' && s2[2]<='C') || (s1[2]>='D' && s2[2]>'D'))
			{
				w3=1;
				if(abs(s1[2]-s2[2])==1)w4=1;
			}
		}
	}
	cout<<w1<<w2<<w3<<w4;
	return 0;
}
