/*小 Z 正在玩一种单人纸牌游戏。
他有一叠特制的纸牌，共有 n 张，从上到下的点数依次为 a1, a2, . . . , an。每张牌的
点数都是 1 到 m 之间的整数，且每种点数都出现至少一次。
小 Z 将进行 n 局相互独立的游戏。每局开始前，他会将所有牌按原顺序放回牌堆，
并清空桌面。在第 i (1 ≤ i ≤ n) 局中，他跳过前 i -1 张牌，依次打出第 i 张到第 n 张
牌，这些牌的点数依次为 ai, ai+1, . . . , an。
桌面上的牌始终从左到右排成一行。打出一张点数为 k 的牌时：
--若桌面上没有点数为 k 的牌，就将这张牌放在最右端；
-- 否则，收走桌面上点数为 k 的牌及其右侧的所有牌，再把这张牌放在最右端。被
收走的牌在本局中不再使用。
由上述规则可知，任意时刻桌面上同一种点数的牌至多只有一张。
最后一张牌打出后，本局游戏结束。
例如，若桌面上从左到右的牌的点数依次为 1, 4, 2，则打出一张点数为 3 的牌后，桌
面上从左到右的牌的点数依次为 1, 4, 2, 3。接着打出一张点数为 4 的牌时，桌面上原来
点数为 4 的牌及其右侧的所有牌（点数依次为 4, 2, 3）被收走，再把新打出的 4 放在最
右端，此时桌面上从左到右的牌的点数依次为 1, 4。
你需要帮助小 Z 依次求出，对于每个 i = 1, 2, . . . , m，在所有 n 局游戏中，有多少
局结束时桌面上留有点数为 i 的牌。

【输入格式】
从文件 card.in 中读入数据。
输入的第一行包含两个正整数 n, m，分别表示牌的数量和点数种类数。
输入的第二行包含 n 个正整数 a1, a2, . . . , an，依次表示小 Z 的牌从上到下的点数。

【输出格式】
输出到文件 card.out 中。
输出一行 m 个非负整数，其中第 i (1 ≤ i ≤ m) 个整数表示在所有 n 局游戏中，有
多少局结束时桌面上留有点数为 i 的牌。
1 ≤ m ≤ 3 × 10^5*/
#include<bits/stdc++.h>
using namespace std;


int main()
{
freopen("card.in","r",stdin);
freopen("card.out","w",stdout);
	int n,m;
	cin>>n>>m;
	int a[n],b[n][n],mj[m]={0};
	for(int i=0;i<=n-1;i++)
		cin>>a[i];
	for(int i=0;i<=n-1;i++)//局 
	{
		for(int j=i;j<=n-1;j++)
		{
			b[i][j]=a[j]; 
			for(int p=i;p<=j-1;p++)
			{
				if(b[i][j]==b[i][p])
				{
					for(int q=p;q<=j-1;q++)b[i][q]=0;
					break;
				}
			}//收牌 
			
		}//打牌
		for(int j=1;j<=m;j++)//fact
			for(int z=i;z<=n-1;z++)
			{
				if(b[i][z]==j)mj[j-1]+=1;
			}//记牌数 
	}
	for(int i=0;i<=m-1;i++)//索引
		cout<<mj[i]<<" ";
	return 0;
}
