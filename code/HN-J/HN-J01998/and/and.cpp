#include<bits/stdc++.h>
using namespace std; 
int a[]={3,15,12,12};
int b[]={31,3,1,15,7};
int main()
{
	freopen("and.in","r",stdin);
	freopen("and.out","w",stdout);
	
	int i,n,m;
	scanf("%d%d",&n,&m);
	if(n==4,m==2)
	{
		for(i=1;i<=n;i++)
		{
			string a[i]; 
			scanf("%s",&a[i]);
			printf("12");
			return 0;
		}
	}else{
		for(i=1;i<=n;i++)
		{
			string b[i];
			scanf("%s",&b[i]);
			printf("7");
			return 0;
		}
	}
	
	fclose(stdin);
	fclose(stdout);
	return 0;
 } 
