#include <bits/stdc++.h>
using namespace std;
int n, x[10000005], d, c, t, u, v, a, b;

int main() {
	cin >> c >> t;
	for (int i = 1; i <= t; i++) {
		cin >> n >> d;
		for (int j = 1; j <= n; j++) {
			cin >> x[n];
			if (v == u)
				a++;
			if (v != u)
				b++;
		}
	}
	cout << a << endl << b;
	return 0;
}