/*
小 Z 正在玩一种单人纸牌游戏。
他有一叠特制的纸牌,共有 n 张,从上到下的点数依次为 a 1 , a 2 , . . . , a n 。每张牌的
点数都是 1 到 m 之间的整数,且每种点数都出现至少一次。
小 Z 将进行 n 局相互独立的游戏。每局开始前,他会将所有牌按原顺序放回牌堆,
并清空桌面。在第 i (1 ≤ i ≤ n) 局中,他跳过前 i − 1 张牌,依次打出第 i 张到第 n 张
牌,这些牌的点数依次为 a i , a i+1 , . . . , a n 。
桌面上的牌始终从左到右排成一行。打出一张点数为 k 的牌时:
• 若桌面上没有点数为 k 的牌,就将这张牌放在最右端;
• 否则,收走桌面上点数为 k 的牌及其右侧的所有牌,再把这张牌放在最右端。被
收走的牌在本局中不再使用。
由上述规则可知,任意时刻桌面上同一种点数的牌至多只有一张。
最后一张牌打出后,本局游戏结束。
例如,若桌面上从左到右的牌的点数依次为 1, 4, 2,则打出一张点数为 3 的牌后,桌
面上从左到右的牌的点数依次为 1, 4, 2, 3。接着打出一张点数为 4 的牌时,桌面上原来
点数为 4 的牌及其右侧的所有牌(点数依次为 4, 2, 3)被收走,再把新打出的 4 放在最
右端,此时桌面上从左到右的牌的点数依次为 1, 4。
你需要帮助小 Z 依次求出,对于每个 i = 1, 2, . . . , m,在所有 n 局游戏中,有多少
局结束时桌面上留有点数为 i 的牌。
【输入格式】
从文件 card.in 中读入数据。
输入的第一行包含两个正整数 n, m,分别表示牌的数量和点数种类数。
输入的第二行包含 n 个正整数 a 1 , a 2 , . . . , a n ,依次表示小 Z 的牌从上到下的点数。
*/
#include "bits/stdc++.h"
using namespace std;
int n, m, a[500005], lst[500005], res[500005], fa[500005], ans[500005];
int find(int x)
{
	return fa[x] = (fa[x] == x?x:find(fa[x]));
}
int main()
{
	cin.tie(0);
	ios::sync_with_stdio(false);
	freopen("card.in", "r", stdin);
	freopen("card.out", "w", stdout);
	cin >> n >> m;
	for(int i = 1;i <= n;i++)
	{
		cin >> a[i];
		fa[i] = i;
	}
	for(int i = n;i >= 1;i--)
	{
		if(lst[a[i]])
		{
			int fx = find(i), fy = find(lst[a[i]]);
			fa[fx] = fy;
		}
		res[find(i)]++;
		lst[a[i]] = i;
	}
	for(int i = 1;i <= n;i++)
	{
		if(find(i) == i)
		{
			ans[a[i]] = res[i];
			res[find(i + 1)] += res[i];
		}
	}
	for(int i = 1;i <= m;i++)
	{
		cout << ans[i] << ' ';
	}
	cout << '\n';
	//cout << "Hello, World!";
	return 0;
}
