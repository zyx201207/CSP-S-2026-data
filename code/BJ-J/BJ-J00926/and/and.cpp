#include <bits/stdc++.h> //100pts
using namespace std;
const int N = 2e5 + 2;
int n, m, a[N], bit[N][32], ans;
bool ok[N];
void work (int x, int i) {
    for (int it = 0; it <= 30; it++) {
        bit[i][it] = (x & 1);
        x >>= 1;
    }
    return;
}
signed main () {
    ios::sync_with_stdio(0); cin.tie(0); cout.tie(0);
    freopen("and.in", "r", stdin);
    freopen("and.out", "w", stdout);
    cin >> n >> m;
    for (int i = 1; i <= n; i++) {
        cin >> a[i];
        ok[i] = 1;
        work(a[i], i);
    }
    for (int i = 30; i >= 0; i--) {
        int cti = 0; 
        for (int p = 1; p <= n; p++) {
            if (bit[p][i] == 1 && ok[p]) {
                cti++;
            }
        }
        if (cti < m) {
            continue;
        }
        else {
            for (int p = 1; p <= n; p++) {
                if (bit[p][i] == 0 && ok[p]) {
                    ok[p] = 0;
                }
            }
        }
    }
    int st = 0;
    for (int p = 1; p <= n; p++) {
        if (ok[p]) {
            st = p;
            break;
        }
    }
    ans = a[st];
    for (int i = 1; i <= n; i++) {
        if (ok[i]) {
            ans &= a[i];
        }
    }
    cout << ans << '\n';
    return 0;
}
