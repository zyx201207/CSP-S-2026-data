#include<bits/stdc++.h>
using namespace std;
int main(){
    freopen("travel.in","r",stdin);
    freopen("travel.out","w",stdout);
    ios::sync_with_stdio(0);
    cin.tie(0);
    cout.tie(0);
    string c,s,cx,sx;
    int x,y,xx,yx,a[100][100]={0};
    cin>>c>>s>>cx>>sx;
    x=(s[0]-'0')*10+(s[1]-'0');
    y=s[2]-'A';
    xx=(sx[0]-'0')*10+(sx[1]-'0');
    yx=sx[2]-'A';
    a[x][y]=1;
    a[xx][yx]=1;
    if(c!=cx)
    {
        cout<<"0000";
        return 0;
    }
    else
    {
        cout<<"1";
        if(x!=xx)
        {
            cout<<"00";
        }
        else
        {
            cout<<"1";
            if(y>=0&&y<=2)
            {
                if(yx>=0&&yx<=2)
                {
                    cout<<"1";
                }
                else
                {
                    cout<<"0";
                }
            }
            else
            {
                if(yx>=0&&yx<=2)
                {
                    cout<<"0";
                }
                else
                {
                    cout<<"1";
                }
            }
        }
    }
    if(y>=0&&y<=2)
    {
        if(yx>=0&&yx<=2)
        {
            if(a[x+1][y]==1||a[x-1][y]==1||a[x][y+1]==1||a[x][y-1]==1)
            {
                cout<<"1";
            }
            else
            {
                cout<<"0";
            }
        }
        else
        {
            cout<<"0";
        }
    }
    else
    {
        if(yx>=0&&yx<=2)
        {
            cout<<"0";
        }
        else
        {
            if(a[x+1][y]==1||a[x-1][y]==1||a[x][y+1]==1||a[x][y-1]==1)
            {
                cout<<"1";
            }
            else
            {
                cout<<"0";
            }
        }
    }
    return 0;
}
