#include <bits/stdc++.h>
using namespace std;
namespace cspj {
    typedef long long ll;
    const int MAXN = 5e5 + 5;
    int n, m, b[MAXN], a[MAXN], ans[MAXN];
    void main() {
        ios::sync_with_stdio(false);
        cin.tie(0), cout.tie(0);
        cin >> n >> m;
        for (int i = 1; i <= n; i++) {
            cin >> a[i];
        }
        if (m == 1) {
            cout << n << "\n";
            return;
        }
        if (m == 2) {
            int cnt = 0;
            for (int i = 1; i <= n; i++) {
                if (a[i] != a[n]) cnt++;
            }
            if (a[n] == 1) cout << n << " " << cnt << "\n";
            else cout << cnt << " " << n << "\n";
            return;
        }
        for (int i = 1; i <= n; i++) {
            stack<int> s;
            for (int j = i; j <= n; j++) {
                while (!s.empty() && b[a[j]]) {
                    b[s.top()]--;
                    s.pop();
                }
                b[a[j]]++;
                s.push(a[j]);
            }
            for (int j = 1; j <= m; j++) {
                ans[j] += b[j];
                b[j] = 0;
            }
        }
        for (int i = 1; i <= m; i++) cout << ans[i] << " \n"[i == m];
    }
}
int main() {
    freopen("card.in", "r", stdin);
    freopen("card.out", "w", stdout);
    cspj::main();
    return 0;
}
