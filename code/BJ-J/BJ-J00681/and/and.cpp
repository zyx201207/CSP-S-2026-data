namespace cspj {
    typedef long long ll;
    const int MAXN = 2e5 + 5;
    int a[MAXN], ans;
    void main() {
        ios::sync_with_stdio(false);
        cin.tie(0), cout.tie(0);
        int n, m;
        cin >> n >> m;
        for (int i = 1; i <= n; i++) {
            cin >> a[i];
        }
        for (int j = 29; j >= 0; j--) {
            int cnt = 0;
            ans += (1 << j);
            for (int i = 1; i <= n; i++) {
                if ((a[i] & ans) == ans) {
                    cnt++;
                }
            }
            if (cnt < m) ans -= (1 << j);
        }
        cout << ans << "\n";
    }
}
