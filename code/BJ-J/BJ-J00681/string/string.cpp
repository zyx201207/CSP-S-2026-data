#include <bits/stdc++.h>
using namespace std;
namespace cspj {
    typedef long long ll;
    const int MAXN = 2e5 + 5;
    struct node {
        ll cnt;
        char c;
    } a[MAXN];
    int n;
    void main() {
        ios::sync_with_stdio(false);
        cin.tie(0), cout.tie(0);
        cin >> n;
        for (int i = 1; i <= n; i++) {
            cin >> a[i].cnt >> a[i].c;
        }
        int l = 1, r = n;
        node lnow = a[l], rnow = a[r];
        ll ans = 0;
        while (l <= r) {
            ll mc = min(lnow.cnt, rnow.cnt);
            lnow.cnt -= mc, rnow.cnt -= mc;
            if (lnow.c != rnow.c) ans += mc;
            if (lnow.cnt == 0) l++, lnow = a[l];
            if (rnow.cnt == 0) r--, rnow = a[r];
        }
        cout << ans << "\n";
    }
}
int main() {
    freopen("string.in", "r", stdin);
    freopen("string.out", "w", stdout);
    cspj::main();
    return 0;
}
