#include<bits/stdc++.h>
using namespace std;
#define int long long
int n,m,a[500005],b[500005],ans = 1;
signed main(){
    freopen("crystal.in","r",stdin);
    freopen("crystal.out","w",stdout);
    cin >> n >> m;
    for(int i = 1;i <= n;i++)
        cin >> a[i];
    sort(a + 1, a + n + 1);
    b[1] = 0;
    for(int i = 2;i <= n;i++){
        if(a[i] == a[i - 1]){
            b[i] = b[i - 1];
            continue;
        }
        b[i] = b[i - 1] + (i - 1) * (a[i] - a[i - 1]);
    }
    for(int i = 1;i <= n;i++){
        if(b[i] == m){
            ans = i;
            for(int j = i + 1;j <= n;j++)if(a[j] == a[i])ans++;
            break;
        }if(b[i] > m){
            ans = i - 1;
            int cnt = 1;
            for(int j = i + 1;j <= n;j++)if(a[j] == a[i])cnt++;
            int x = m - b[ans],y = a[i] - a[ans],z = i;
            for(int j = 1;j <= z;j++){
                x += a[z] - a[j];
                int xy = min(x / y,z - j);
                ans = max(ans,cnt + xy);
            }
            break;
        }
    }
    cout << ans;
    return 0;
}
