#include<bits/stdc++.h>
using namespace std;
const int N=5010,M=2e6+10;
long long x[M],dp[N][N],l[M],r[M],z[N],s[N][N];
int main()
{
	freopen("migrate.in","r",stdin);
	freopen("migrate.out","w",stdout);
	ios::sync_with_stdio(0);
	cin.tie(0);
	cout.tie(0);
	int c,t;
	cin>>c>>t;
	if(c==11||c==12)
	{
		while(t--)
		{
			long long n,d,p,i;
			cin>>n>>d;
			for(i=1;i<=n;i++)
				cin>>x[i];
			p=d/(x[2]-x[1]);
			if(p==1||p==0)
				cout<<0<<'\n';
			else
				cout<<max(0ll,n-p-p+1)<<'\n';
		}
		return 0;
	}
	if(c==13||c==14)
	{
		while(t--)
		{
			long long d,n,i,j,cnt=0,k1=0,k2=0;
			cin>>n>>d;
			for(i=1;i<=n;i++)
			{
				cin>>x[i];
				l[i]=r[i]=0;
			}
			for(i=1;i<=n;i++)
			{
				if((x[i]-x[1])<=d&&(x[n]-x[i])<=d)
				{
					cnt++;
					if(k1==0)
						k1=i;
					else
						k2=i;
				}
			}
			if(cnt>=3||n<=3)
			{
				cout<<0<<'\n';
				continue;
			}
			l[1]=1;
			for(i=2;i<=n;i++)
			{
				for(j=l[i-1];j<i;j++)
				{
					if((x[i]-x[j])<=d)
					{
						l[i]=j;
						break;
					}
				}
			}
			l[1]=0;
			r[n]=n;
			for(i=n-1;i>=1;i--)
			{
				for(j=r[i+1];j>i;j--)
				{
					if((x[j]-x[i])<=d)
					{
						r[i]=j;
						break;
					}
				}
			}
			r[n]=0;
			if(cnt==2)
			{
				if((x[k2+1]-x[k1-1])>d)
					cout<<(k1-1)*(k2-1)<<'\n';
				else
					cout<<(l[k2+1]-1)*(n-r[k1-1])<<'\n';
				continue;
			}
			if((x[k1+1]-x[k1-1])>d)
				cout<<0<<'\n';
			else
			{
				if(k1==2)
					cout<<n-r[1]<<'\n';
				else if(k1==(n-1))
					cout<<l[n]-1<<'\n';
				else
					cout<<(l[k1+1]-1)*(r[k1-1]-r[k1-2])+(n-r[k1-1])*(l[k1+2]-l[k1+1])<<'\n';
			}
		}
		return 0;
	}
	while(t--)
	{
		long long d,ans=0,n,i,j,k;
		cin>>n>>d;
		for(i=1;i<=n;i++)
		{
			cin>>x[i];
			l[i]=0;
		}
		l[1]=1;
		for(i=2;i<=n;i++)
		{
			for(j=l[i-1];j<i;j++)
			{
				if((x[i]-x[j])<=d)
				{
					l[i]=j;
					break;
				}
			}
		}
		l[1]=0;
		for(i=1;i<=n;i++)
		{
			dp[i][0]=1;
			s[i][0]=1;
			z[i]=1;
			for(j=i+1;j<=n;j++)
			{
				if(l[j]==0)
					break;
				for(k=z[j-1];k<=n;k++)
				{
					dp[j][k]=s[j-1][k-1]-s[max(i,l[j])-1][k-1];
					if(dp[j][k]>2)
						dp[j][k]=3;
					s[j][k]=s[j-1][k]+dp[j][k];
					if(dp[j][k]>0)
					{
						if(dp[j][k]==2)
							ans++;
						z[j]=k;
						break;
					}
				}
				s[j][z[j]-1]=s[j-1][z[j]-1];
			}
			z[i]=0;
			for(j=i;j<=n;j++)
			{
				dp[j][z[j]]=0;
				s[j][z[j]]=s[j][max(0ll,z[j]-1)]=0;
				z[j]=0;
			}
		}
		cout<<ans<<'\n';
	}
	return 0;
}
