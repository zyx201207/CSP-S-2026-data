inline ll read(){
	ll x=0,f=1,ch=getchar();
	while(!isdigit(ch)){if(ch=='-')f=-1;ch=getchar();}
	while(isdigit(ch))x=(x<<1)+(x<<3)+(ch^48),ch=getchar();
	return x*f;
}
inline void wt(int x){
	if(x<0)x=-x,putchar('-');
	if(x>9)wt(x/10),x%=10;
	putchar(x+48);
}
inline void wtsp(int x){
	wt(x),putchar(' ');
}
inline void wtln(int x){
	wt(x),putchar('\n');
}
