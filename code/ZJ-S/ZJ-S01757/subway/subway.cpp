#include<bits/stdc++.h> 
#define int long long 
using namespace std;

const int M = 5e5 + 5, N = 5e2 + 5, INF = 0x3f3f3f3f3f3f3f3f;

int c, n, m, d, q, w[M];
struct sta { int t, idx; };
vector<sta> vec[M];
int dis[N][N];

signed main() {
	freopen("subway.in", "r", stdin);
	freopen("subway.out", "w", stdout); 
	// freopen("subway.in", "r", stdin);
	// freopen("subway.out", "w", stdout); 
	cin.tie(nullptr)->sync_with_stdio(false);
	
	cin >> c >> n >> m >> d >> q;
	// 这个 d 和 c 的输入好像没什么用, 这个 Quiet Light 的主题可爱捏
	for (int i = 1; i <= m; ++i) cin >> w[i];
	// 这个好像纯增加读题难度
	for (int i = 1; i <= n; ++i) {
		int k; cin >> k;
		for (int j = 1; j <= k; ++j) {
			int a, t; cin >> a >> t;
			vec[a].push_back({t, i});
		}
	}
	// 输入结束

	memset(dis, 0x3f, sizeof dis);
	for (int i = 1; i <= n; ++i) dis[i][i] = 0;
	// 欸，我好像不会建图喵。。。直接暴力枚举 k？
	// 经过我的异通乱算这个的时间复杂度好像是 O(dm) 的，可以通过
	for (int i = 1; i <= m; ++i) {
		for (int j = 0; j < (int)vec[i].size(); ++j)
			for (int k = j + 1; k < (int)vec[i].size(); ++k) {
				int u = vec[i][j].idx, v = vec[i][k].idx;
				int tim = vec[i][j].t + vec[i][k].t;
				dis[u][v] = dis[v][u] = min(dis[u][v], tim);
			}
	}
	for (int k = 1; k <= n; ++k)
		for (int j = 1; j <= n; ++j)
			for (int i = 1; i <= n; ++i)
				dis[i][j] = min(dis[i][j], dis[i][k] + dis[j][k]);
	// 这里其实可优化常数，写完再改

	while (q--) {
		int x, y; cin >> x >> y;
		// 这个 del 用起来好奇怪啊喵
		int ans = INF;
		for (int i = 0; i < (int)vec[x].size(); ++i)
			for (int j = 0; j < (int)vec[y].size(); ++j) {
				int u = vec[x][i].idx, v = vec[y][j].idx;
				int tim = vec[x][i].t + vec[y][j].t;
				ans = min(ans, tim + dis[u][v]);
			}
		cout << ans + w[x] + w[y] << '\n';
	}
	// 16:00 写完喵
	return 0;
}

