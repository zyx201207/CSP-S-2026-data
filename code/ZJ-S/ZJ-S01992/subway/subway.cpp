#include<bits/stdc++.h>
using namespace std;
const long long inf=1e18;
int c,n,m,d,q; 
int nm;
int ww[500050]; 
long long dp[550][550];
struct edge{
	int v,w;
};
vector<edge> e[500050];
int sz[500050];
void solve(){
	int s,t;
	cin>>s>>t;
	long long ans=inf;
	for(int i=0;i<sz[s];i++)
		for(int j=0;j<sz[t];j++)
			ans=min(ans,dp[e[s][i].v][e[t][j].v]+ww[s]+ww[t]+e[s][i].w+e[t][j].w); 
	cout<<ans<<'\n';
} 
int main(){
    freopen("subway.in","r",stdin);
    freopen("subway.out","w",stdout);
    ios::sync_with_stdio(false);
    cin.tie(0),cout.tie(0);
	cin>>c>>n>>m>>d>>q;
	for(int i=1;i<=m;i++) cin>>ww[i];
	for(int i=1,x;i<=n;i++){
		cin>>x;
		for(int j=1,v,t;j<=x;j++){
			cin>>v>>t;
			e[v].push_back({i,t});
			sz[v]++;
		}
	}
	for(int i=1;i<=n;i++) for(int j=1;j<=n;j++) dp[i][j]=inf;
	for(int i=1;i<=n;i++) dp[i][i]=0;
	for(int k=1;k<=m;k++)
		for(int i=0;i<sz[k]-1;i++)
			for(int j=i+1;j<sz[k];j++)
				dp[e[k][i].v][e[k][j].v]=min(dp[e[k][i].v][e[k][j].v],e[k][i].w*1ll+e[k][j].w*1ll),dp[e[k][j].v][e[k][i].v]=min(dp[e[k][j].v][e[k][i].v],e[k][i].w*1ll+e[k][j].w*1ll);
	for(int k=1;k<=n;k++)
		for(int i=1;i<=n;i++)
			for(int j=1;j<=n;j++)
				dp[i][j]=min(dp[i][k]+dp[k][j],dp[i][j]);
	while(q--) solve();
    return 0;
}
