#include <bits/stdc++.h>
using namespace std;
long long a[514514],b[514514];
int main(){
	freopen("crystal.in","r",stdin);
	freopen("crystal.out","w",stdout);
	long long n,m;
	cin >> n >> m;
	for(long long i = 1;i<=n;i++){
		cin >> a[i];
	}
	sort(a+1,a+n+1);
	long long x = 1,ans = -100000000;
	for(long long j = 2;j<=n;j++){
		for(long long i = j;i<=n;i++){
			b[i] = a[i]-a[i-1];
			if(b[i]*x+b[i-1]<=m){
				b[i] = b[i]*x+b[i-1];
				x++;
				//cout << x << " ";
			}
			else{
				ans = max(ans,x);
				x = 1;
				//cout << b[i-1] << endl;
			}
		}
		x = 1;
		b[j] = a[j]-a[j-1];
	}
	cout << ans;
	return 0;
}
