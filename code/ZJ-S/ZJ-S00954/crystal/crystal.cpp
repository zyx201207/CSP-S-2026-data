using namespace std;
void read(ll &x){
	ll f=1;x=0;char s=getchar();
	while(s<'0'||s>'9'){if (s=='-'){f=-f;}s=getchar();}
	while (s>='0'&&s<='9'){x=x*10+s-'0';s=getchar();}
	x*=f;
}
const ll N=5e5+5;
ll n,m;
ll a[N],s[N];
bool check(ll x,ll i){
	ll u=i-x,tot=s[i-1]-s[x-1];
	return u*a[i]-tot<=m;
}
int main(){
	freopen("crystal.in","r",stdin);
	freopen("crystal.out","w",stdout);
	read(n);read(m);
	for (ll i=1;i<=n;i++)read(a[i]);
	sort(a+1,a+n+1);
	for (ll i=1;i<=n;i++){
		s[i]=s[i-1]+a[i];
	}
	ll ans=1;
	for (ll i=1;i<=n;i++){
		ll l=1,r=i,now;
		while (l<=r){
			ll mid=(l+r)>>1;
			if (check(mid,i)){
				now=mid;
				r=mid-1;
			}
			else l=mid+1;
		}
		ans=max(ans,i-now+1);
	}
	printf("%lld",ans);
	return 0;
}

