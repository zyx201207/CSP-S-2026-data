/*
旅游（travel）
小 R 和小 X 准备坐高铁出门旅游。他们买了两张二等座车票，车票上写着各自的
车厢号和座位号。两人希望座位相邻，这样旅途中可以坐在一起。
他们乘坐的列车由 17 节车厢组成，车厢编号是 01 到 17。其中，01 和 16 号车厢
是一等座车厢，其余车厢是二等座车厢。两人买的都是二等座车票，座位都在二等座车
厢中。每节二等座车厢共有 18 排，每排有 5 个座位。座位号由两位排号和一位大写字
母组成，例如 03C 表示第 3 排 C 座。每一排的座位按照从左到右的顺序排列，座位字
母依次是 A、B、C、D、F，其中 C 座与 D 座之间是过道，即每排过道左侧的座位序列
是 A、B、C，右侧是 D、F。
两个座位相邻，当且仅当在同一节车厢的同一排，位于过道的同一侧，且在该侧的
座位序列中相邻。
你需要帮助小 R 依次判断：
两张车票对应的座位是否在同一节车厢；
两张车票对应的座位是否在同一节车厢的同一排；
两张车票对应的座位是否在同一节车厢的同一排，且位于过道的同一侧；
两张车票对应的座位是否相邻。
【输入格式】
从文件 travel.in 中读入数据。
输入的第一行包含四个字符串 c1, s1, c2, s2，分别表示小 R 的车票上的车厢号、座位
号，以及小 X 的车票上的车厢号、座位号。
【输出格式】
输出到文件 travel.out 中。
输出一行一个长度为 4 的 01 字符串，分别表示四个问题的答案，其中 1 代表是，
0 代表否
*/
#include<bits/stdc++.h>
using namespace std;
int a,x;
string b,y;
int main(){
	freopen("travel.in","r",stdin);
	freopen("travel.out","w",stdout);
	cin>>a>>b>>x>>y;
	if(a==x){
		cout<<"1";
	}else{
		cout<<"0000";
		return 0;
	}
	if(b[0]==y[0]&&b[1]==y[1]){
		cout<<"1";
	}else{
		cout<<"000";
		return 0;
	}
	if(y[2]<='C'&&b[2]<='C'){
		cout<<"1";
	}else if(y[2]<='F'&&y[2]>='D'&&b[2]<='F'&&b[2]>='D'){
		cout<<"1";
	}else{
		cout<<"00";
		return 0;
	}
	char r=b[2],t=y[2];
	if(r=='A'&&t=='B'){
		cout<<"1";
	}else if(r=='B'&&t=='A'){
		cout<<"1";
	}else if(r=='B'&&t=='C'){
		cout<<"1";
	}else if(r=='C'&&t=='B'){
		cout<<"1";
	}else if(r=='D'&&t=='F'){
		cout<<"1";
	}else if(r=='F'&&t=='D'){
		cout<<"1";
	}else{
		cout<<"0";
	}
	return 0;
}
