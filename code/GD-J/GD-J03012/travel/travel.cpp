#include<bits/stdc++.h>
using namespace std;
int main(){
	//freopen("travel.in","r",stdin);
	//freopen("travel.out","w",stdout);
	/* 	 
		
		
		输出一行一个长度为 4 的 01 字符串，分别表示四个问题的答案，其中 1 代表是，0 代表否。
		*/
	long long a,b;//小 R 的车票上的车厢号a、座位号ac，以及小 X 的车票上的车厢号b、座位号bc。
	string ac,bc;
	cin>>a>>ac>>b>>bc;
	if(a==b){//两张车票对应的座位是否在同一节车厢；
		cout<<1;
	}else{
		cout<<0;
	}
////////////////////////////////////////////////////////////////////////////////////////////////
	int q=(ac[0]-'0')*10+ac[1]-'0';
	int p=(bc[0]-'0')*10+bc[1]-'0';
	if(q==p){//两张车票对应的座位是否在同一节车厢的同一排；
		cout<<1;
	}else{
		cout<<0;
	}
	int op=0;
	/////////////////////////////////////////////////////////////////////////////////////////
	if(q==p){//&&(ac[2]==bc[2])
	//两张车票对应的座位是否在同一节车厢的同一排，且位于过道的同一侧；
		if((a==b)&&(ac[2]=='D'||ac[2]=='F')&&(bc[2]=='D'||bc[2]=='F')){
			cout<<1;
			op=1;
		}else{
				if((ac[2]=='B')||(ac[2]=='C')||(ac[2]=='A')){
			  		if((bc[2]=='B')||(bc[2]=='C')||(bc[2]=='A')){
			  			cout<<1;
				  	}else{
				  		cout<<0;
					}
				}else{
				  	cout<<0;
				}}
	}else{
		op=0;
		cout<<0;
	}
	///////////////////////////////////////////////////////////////////////////////////
	//两张车票对应的座位是否相邻。
	if(p==q){//同排
			if(op)//同排同侧
			{//是否相邻 
				if((ac[2]=='F'&&bc[2]=='D')||(bc[2]=='F'&&ac[2]=='D')){
					cout<<1;
				}else if((ac[2]+1==bc[2])||(ac[2]-1==bc[2])){
					cout<<1;
				}else{
					cout<<0;
				}
			}else{
		cout<<"0"<<" "<<endl;
	}	 
	}else{
		cout<<0;
	}
	return 0;
} 
