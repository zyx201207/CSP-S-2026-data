#include <bits/stdc++.h>
using namespace std;
int n,m,a[500005],result[500005],q[500005],t;
// 若桌面上没有点数为k的牌，就将这张牌放在最右端；
//? 否则，收走桌面上点数为k的牌及其右侧的所有牌，再把这张牌放在最右端。被
//收走的牌在本局中不再使用。
//由上述规则可知，任意时刻桌面上同一种点数的牌至多只有一张。
//最后一张牌打出后，本局游戏结束。
//例如，若桌面上从左到右的牌的点数依次为1,4,2，则打出一张点数为3的牌后，桌
//面上从左到右的牌的点数依次为1,4,2,3。接着打出一张点数为4的牌时，桌面上原来
//点数为4的牌及其右侧的所有牌（点数依次为4,2,3）被收走，再把新打出的4放在最
//右端，此时桌面上从左到右的牌的点数依次为1,4。
//你需要帮助小Z依次求出，对于每个i=1,2,...,m，在所有n局游戏中，有多少
//局结束时桌面上留有点数为i的牌
int main(){
	freopen("card.in","r",stdin);
	freopen("card.out","w",stdout);
	cin >> n>>m;
	for (int i=1;i<=n;i++){
		cin >> a[i];
	}
	for (int i=1;i<=n;i++){//n局游戏 
		t = 0;
		for (int j=i;j<=n;j++){//第i局 
		    int flag=1;
			for (int k=1;k<=t;k++){//判断队列Q中是否含有当前牌 
				if (q[k] == a[j]){//如果有就将队尾移到k的位置 
					t = k;
					flag=0;
					break;
				}
			}
			if (flag)q[++t]=a[j];//否则将当前牌入队 
		}
		if (t){//若对列不空 
			for (int i=1;i<=t;i++){
//				cout << q[i]<<" ";
				result[q[i]]++;//将队列内牌对应局数++ 
			}
		}
		memset(q,0,sizeof(q));//清空队列 
	} 
	for (int i=1;i<=m;i++){
		cout << result[i]<<" ";
	}
	return 0;
}
