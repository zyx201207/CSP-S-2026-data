int last[N] , out[N] , ans[N];//注意这里的ans存的是不在桌面上的回合数，out表示最近一次退出是什么时候
//退出
//如果这个数不在桌面上那么last_i=0 
int a[N] , n , m;
int ve[N] , end;//模拟vector
void Push(int val , int now){//加入vector 
	ve[++ end] = val;
	last[val] = now;
	ans[val] += (now - out[val] - 1);//计算退出时间 
//	printf("%lld %lld %lld\n" , val , now , out[val]);
} 
void Kill(int where , int now){//从第i位开始删除 
	for(int i = where + 1;i <= end;i ++){//里面的数被删除了 
		last[ve[i]] = 0;
		out[ve[i]] = now;//更新退出时间 
	}
	end = where;
}
