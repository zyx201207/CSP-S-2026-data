int main()
{
	freopen("travel.in","r",stdin);
	freopen("travel.out","w",stdout);
	string a,s1,b,s2;
	cin>>a>>s1>>b>>s2;
	if(a==b)
	{
		cout<<"1";
		if(s1[0]==s2[0])
		{
			if(s1[1]==s2[1])
			{
				cout<<"1";
				if((s1[2]=='C'&&s2[2]=='D')||(s1[2]=='D'&&s2[2]=='C'))
				{
					cout<<"00";
				}
				else
				{
					if((int(s1[2]-'A')<=2&&int(s2[2]-'A')<=2)||(int(s1[2]-'A')>=3&&int(s1[2]-'A')>=3))
					{
						cout<<"1";
						if(s1[2]-'A'==s2[2]-'A'+1||s1[2]-'A'+1==s2[2]-'A')
						{
							cout<<"1";
						}
						else
						{
							cout<<"0";
						}
					}
					else
					{
						cout<<"00";
					}
				}
			}
			else
			{
				cout<<"000";
			}
		}
		else
		{
			cout<<"000";
		}
	}
	else
	{
		cout<<"0000";
	}
	return 0;
 }
