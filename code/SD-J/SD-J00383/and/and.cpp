#include <bits/stdc++.h>

using namespace std;
long long n,m,a[200010],ans=-1,c,q=int(2e31-1);
void czx(int s){
	if(m-c>n-s+1){
		return ;
	}
	if(c==m){
		if(q>ans){
			ans=q;
		}
		return ;
	}
	int w=q;
	q&=a[s];
	c++;
	czx(s+1);
	c--;
	q=w;
	czx(s+1);
	return ;
}
bool ppp(int x){
	while(x%2==0){
		x/=2;
	}
	if(x==1){
		return true;
	}
	else{
		return false;
	}
}
int main()
{
	freopen("and.in","r",stdin);
	freopen("and.out","w",stdout);
	cin>>n>>m;
	long long qq=int(2e31-1),ma=-1;
	for (int i=1;i<=n;i++){
		cin>>a[i];
	}
	for (int i=1;i<=n;i++){
		qq&=a[i];
		ma=max(ma,a[i]);
	}
	if(n<=20){
		czx(1);
		cout<<ans;
	}
	else if(n>20&&n<=2000){
		if(m==n){
			cout<<qq;
		}
		else if(m==1){
			cout<<ma;
		}
		else if(m==2){
			for (int i=1;i<n;i++){
				for (int j=i+1;j<=n;j++){
					if(a[j]&a[i]>ans){
						ans=a[j]&a[i];
					}
				}
			}
			cout<<ans;
		}
	}
	else if(n>2000){
		if(qq==ma){
			sort(a+1,a+n+1);
			cout<<a[n-m+1];
		}
		else if(ppp(n)){
			for (int i=n;i>=n-m+1;i--){
				q=q&(i-1);
			}
			cout<<q;
		}
		else if(m==n-1){
			cout<<qq;
		}
	}
	return 0;
}
