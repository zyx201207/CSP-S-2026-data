#include<bits/stdc++.h>
using namespace std;
int n,m,ans[300100],A[500100],i,book[500100],B[300100],j,t,C[500100];
int main(){
	freopen("card.in","r",stdin);
	freopen("card.out","w",stdout);
	scanf("%d%d",&n,&m);
	for(i=1;i<=n;i++){
		scanf("%d",&A[i]);
	}
	for(i=1;i<=n;i++){
		t=i;
		while(A[i]==A[i+1]){
			C[t]=i-t;
			i++;
		}
		if(C[t]%2==1){
			C[t]--;
		}
		else{
			C[t]-=2;
		}
	}
	for(i=n;i>=1;i--){
		if(B[A[i]]==0){
			book[i]=-1;
			B[A[i]]=i;
		}
		else{
			book[i]=B[A[i]];
			B[A[i]]=i;
		}
	}
	for(i=1;i<=n;i++){
		if(C[i]>0){
			for(j=i;j<=n;j++){
				if(C[j]>0){
					j+=C[j]-1;
					continue;
				}
				if(book[j]==-1){
					ans[A[j]]+=C[i];
				}
				else{
					j=book[j]-1;
				}
			}
			i+=C[i]-1;
			continue;
		}
		else{
			for(j=i;j<=n;j++){
				if(C[j]>0){
					j+=C[j]-1;
					continue;
				}
				if(book[j]==-1){
					ans[A[j]]++;
				}
				else{
					j=book[j]-1;
				}
			}
		}
	}
	for(i=1;i<=m;i++){
		printf("%d ",ans[i]);
	}
	fclose(stdin);
	fclose(stdout);
}
