//天长地久有时尽，此恨绵绵无绝期。 
#include<bits/stdc++.h>
using namespace std;
long long n,m,past=1,a[500005],cnt[300005],last[300005],d[500005],ans[300005],sum[500005]; 
int main(){
	freopen("card.in","r",stdin);
	freopen("card.out","w",stdout);
	cin>>n>>m;
	for(long long i=1;i<=n;i++){
		cin>>a[i];
		cnt[a[i]]++;
		last[a[i]]=i;
	} 
	for(long long i=1;i<=n;i++){
		d[i]++;
		if(cnt[a[i]]!=1&&last[a[i]]!=i){
			for(long long j=past;j<=i;j++){
				sum[j]=sum[j-1]+d[j];
			}
			past=i+1;
			d[i+1]-=sum[i];
			d[last[a[i]]+1]+=sum[i];
		}
	} 
	for(long long i=past;i<=n;i++){
		sum[i]=sum[i-1]+d[i];
	}
	for(long long i=1;i<=n;i++){
		ans[a[i]]+=sum[i];
	}
	for(long long i=1;i<=m;i++){
		cout<<ans[i]<<" ";
	}
	return 0;
}
