#include<bits/stdc++.h>
using namespace std;
int main()
{
	freopen("travel.in","r",stdin);
	freopen("travel.out","w",stdout);
	int c1,c2;
	string s1,s2,sg="";
	cin>>c1>>s1>>c2>>s2; 
	if(c1==c2)
	{
		sg=sg+"1";
		if(s1[0]==s2[0]&&s1[1]==s2[1])
		{
			sg=sg+"1";
			if(s1[2]<='C'&&s2[2]<='C')
			{
				sg=sg+"1";
				if(s1[2]>s2[2])
				{
					if(s1[2]-s2[2]==1)
					{
						sg=sg+"1";
					}
					else
					{
						sg=sg+"0";
					}
				}
				else
				{
					if(s2[2]-s1[2]==1)
					{
						sg=sg+"1";
					}
					else
					{
						sg=sg+"0";
					}
				}
			}
			else
			{
				if(s1[2]>'C'&&s2[2]>'C')
				{
					sg=sg+"11";
				}
				else
				{
					sg=sg+"00";
				}
			}
		}
		else
		{
			sg=sg+"000";
		}
	}
	else
	{
		sg="0000";
	}
	cout<<sg;
	return 0;
}
