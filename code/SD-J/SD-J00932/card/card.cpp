#include <bits/stdc++.h>
using namespace std;
const int N=500005,M=300005;
int n,m,a[N],last[M],next[N],cnt[M];
int main()
{
	freopen("card.in","r",stdin);
	freopen("card.out","w",stdout);
	ios_base::sync_with_stdio(0);
	cin.tie(0);
	cout.tie(0);
	cin>>n>>m;
	for(int i=1;i<=n;i++)
	{
		cin>>a[i];
		next[last[a[i]]]=i;
		last[a[i]]=i;
	}
	for(int i=1;i<=n;i++)
	{
		for(int j=i;j<=n;j++)
		{
			if(next[j]!=0)
				j=next[j]-1;
			else
				cnt[a[j]]++;
		}
	}
	for(int i=1;i<=m;i++)
		cout<<cnt[i]<<' ';
	return 0;
}
