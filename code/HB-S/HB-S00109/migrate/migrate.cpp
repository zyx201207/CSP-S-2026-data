#include <bits/stdc++.h>

using namespace std;
int main()
{
    int c, t, n, d, x[2000000];
    cin >> c >> t;
    for (int i = 1;i <= t;i++)
    {
        cin >> n >> d;
        for (int j = 1;j <= n;i++)
        {
            x[j] = j;
        }
    }
    freopen("crystal.in","r",stdin);
    freopen("crystal.out","w",stdout);
    return 0;
}
