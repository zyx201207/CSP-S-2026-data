#include<bits/stdc++.h>
using namespace std;
using ll=long long;
int main(){
	freopen("crystal.in","r",stdin);
	freopen("crystal.out","w",stdout);
	ios::sync_with_stdio(0);
	cin.tie(0),cout.tie(0);
	
	ll N,M;
	cin>>N>>M;
	
	ll a[N+5];
	for(int i=1;i<=N;i++){
		cin>>a[i];
	}
	
	sort(a+1,a+N+1);
	
	ll s[N+5],c[N+5];
	c[1]=0;
	for(int i=2;i<=N;i++){
		s[i]=a[i]-a[i-1];
		c[i]=s[i]+c[i-1];
	}
	
	
//	for(int i=2;i<=N;i++)cout<<c[i]<<' ';
//	cout<<'\n';
	
	
	ll ans=1,cost=0;
	
	for(ll l=1,r=1;;){
		if(r==N)break;
		if(l>=r)r++;
		if(cost+(r-l+1)*s[r+1]<M){
			cost+=(r-l+1)*s[r+1];
			r++;
		}else{
			cost-=c[r]-c[l-1];
			l++;
		}
		ans=max(ans,r-l+1);
//		cout<<l<<' '<<r<<' '<<cost<<'\n';
	}
	
	cout<<ans;
	
	return 0;
}

