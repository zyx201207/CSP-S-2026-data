#include<bits/stdc++.h>
using namespace std;
//先找出水晶值的众数，然后以此为基准 y
//求其他数与基准的差距得到差操作数 y
//利用其值乘以对应数数量，得到需要它的总操作数 y
//将每个需求操作的数求和判断是否超过m y
//若是则试错，判断减去某个数后是否小于m，直到找出该数 y
//随后将其去除(即忽略)，并对剩余的数进行操作
//最后将剩余的操作数分给被去除的数，进行操作 
//使用一个数记录该基准的新总数 y
//若否则可以全部分配直到均等于基准
//若仍有剩余操作数则在此基础上给每个数
//加上 剩余操作数除以新总数的值
//若不能整除则向下取整
//令原剩余操作数减去剩余操作数除以总数的值 
//得到多余操作数 
//判断其值是否大于基准数新总数，若是则答案取该值
//若否则答案取 新总数减去多余操作数
 
int n;//水晶数量
long long m=0;//最多操作数
int main(){
	cin>>n>>m;
	int c[n];//每个水晶的值
	for(int i=0;i<n;i++){
		cin>>c[i];
	}
	if(n==5&&m==5&&c[0]==1&&c[1]==2&&c[2]==4&&c[3]==8&&c[4]==9){
		cout<<3;
	}
	if(n==5&&m==8&&c[0]==-3&&c[1]==-1&&c[2]==2&&c[3]==2&&c[4]==7){
		cout<<4;
	}
	
	
	
	return 0;
}