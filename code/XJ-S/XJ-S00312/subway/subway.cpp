#include<bits/stdc++.h>
using namespace std;
int w[500005],a[505][5005],t[505][5005],k[505];
int main()
{
	freopen("subway.in","r",stdin);
	freopen("subway.out","w",stdout);
	int c,n,m,d,q,j,s,e,ans,x,y,yy,i,f=0;
	cin>>c>>n>>m>>d>>q;
	for(i=1;i<=m;i++)
	{
		cin>>w[i];
	}
	for(i=1;i<=n;i++)
	{
		cin>>k[i];
		for(j=1;j<=k[i];j++)
		{
			cin>>a[i][j]>>x;
			t[i][a[i][j]]=x;
		}
	}
	for(i=1;i<=q;i++)
	{
		cin>>s>>e;
		ans=0;
		f=0;
		ans=ans+w[s]+w[e];
		if(t[1][s]!=0)
		{
			if(t[2][s]!=0)
			{
				if(t[1][s]>t[2][s])
				{
					x=2;
				}
				else
				{
					x=1;
				}
			}
			else
			{
				x=1;
			}
		}
		if(t[1][s]==0)
		{
			x=2;
		}
		for(y=s;y<=e;y++)
		{
			if(t[1][y]!=0)
			{
				if(t[2][y]!=0)
				{
					if(t[1][y]>t[2][y]&&(t[2][y]+t[1][y])<t[1][y])
					{
						ans=ans+t[2][y];
						if(x!=2)
						{
							ans=ans+t[1][y];
							x=2;
						}
					}
					else
					{
						ans=ans+t[1][y];
						if(x!=1)
						{
							ans=ans+t[2][y];
							x=1;
						}
					}
				}
				else
				{
					ans=ans+t[1][y];
					if(x!=1)
					{
						ans=ans+t[2][y];
						x=1;
					}
				}
			}
			else
			{
				ans=ans+t[2][y];
				if(x!=2)
				{
					ans=ans+t[1][y];
					x=2;
				}
			}
		}
		cout<<ans<<endl;
	}
	return 0;
 } 
