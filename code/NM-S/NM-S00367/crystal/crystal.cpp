int main() {
	freopen("crystal.in","r",stdin);
	freopen("crystal.out","w",stdout);

	int n;
	long long m;
	cin >> n >> m;
	vector<long long> a(n+1);
	for(int i =1 ; i <= n ; i++) {
		cin >> a[i];
	}

	sort(a.begin(),a.end(),greater<int>());

	long long ans = -1;
	for(int i = 1; i<=n; i++) {
		vector<long long> cur(a);
		long long curans = 0;
		for(int j = i ; j >= 1 ; j--) {
			if(cur[j] != a[i]) {
				cur[j]++;
				m--;
			}
			if(m >= 0) {
				curans++;
			}
		}
		ans = max(ans,curans);
	}

	cout << ans << endl;

	return 0;
}
