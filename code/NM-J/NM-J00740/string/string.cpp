#include<bits/stdc++.h>
using namespace std;
int n,maxx=0,b=0;
char m1[200001],a[100000003];
int m0[200001];
int main(){
	freopen("string.in","r",stdin);
	freopen("string.out","w",stdout);
	cin>>n;
	if(n==1){
		cout<<0;
		return 0;
	}
	for(int i=1;i<=n;i++){
		cin>>m0[i]>>m1[i];
	}
	
	for(int i=1;i<=n;i++){
		for(int j=1;j<=m0[i];j++){
			b++;
			a[b]=m1[i];
		}
	}
	int c=0;
	for(int i=1;i<=b/2;i++){
		if(a[i]!=a[b-c]){
			maxx++;
		}
		c++;
	}
	cout<<maxx;
	fclose(stdin);
	fclose(stdout);
}
