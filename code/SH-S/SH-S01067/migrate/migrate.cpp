#include <bits/stdc++.h>
using namespace std;

typedef long long ll;
ll cccc, tttt, n, d, x[2000009];

void solve() {
    cin >> n >> d;
    for(ll i = 1; i <= n; i++) cin >> x[i];
}

int main() {
    freopen("migrate.in", "r", stdin);
    freopen("migrate.out", "w", stdout);
    cin.tie(0)->sync_with_stdio(0);
    cin >> cccc >> tttt;
    while(tttt--) solve();
    return 0;
}