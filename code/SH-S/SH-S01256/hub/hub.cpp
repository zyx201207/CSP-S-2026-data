#include<bits/stdc++.h>
using namespace std;
int main()
{
	freopen("hub.in","r",stdin);
	freopen("hub.out","w",stdout);
	int c,t,i,n,k,u,v;
	scanf("%d %d",&c,&t);
	while(t--)
	{
		scanf("%d %d",&n,&k);
		for(i=1;i<=n;++i)
			scanf("%d %d",&u,&v);
		printf("%d\n",0);
	}
	fclose(stdin);
	fclose(stdout);
	return 0;
}
