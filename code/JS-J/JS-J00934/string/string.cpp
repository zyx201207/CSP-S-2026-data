#include<bits/stdc++.h>
using namespace std;
long long n,ans,a[200005],ji=0,upi,doi,aa,jii;
bool fii,fl;
char ch[200005];
int main()
{
	freopen("string.in","r",stdin);
	freopen("string.out","w",stdout);
	cin>>n;
	for(long long i=1;i<=n;i++)
	{
		cin>>a[i]>>ch[i];
	}
	upi=1;
	doi=n;
	while(upi<doi)
	{
		fl=false;
		if(ji!=0)
		{
			fl=true;
			if(fii)
			{
				while(ji!=0&&upi<doi)
				{
					if(ch[upi]==ch[doi])
					{
						if(ji==a[upi])
						{
							upi++;
							ji=0;
						}
						else
						{
							aa=a[upi];
							jii=ji;
							a[upi]-=min(aa,jii);
							ji-=min(aa,jii);
							if(ji>0)
							{
								upi++;
							}
						}
						
					}
					else
					{
						if(ji==a[upi])
						{
							ans+=ji;
							upi++;
							ji=0;
						}
						else
						{
							aa=a[upi];
							jii=ji;
							ans+=min(aa,jii);
							ji-=min(aa,jii);
							a[upi]-=min(aa,jii);
							if(ji>0)
							{
								upi++;
							}	
						}
					}
				}
			}
			else
			{
				while(ji!=0&&upi<doi)
				{
					if(ch[upi]==ch[doi])
					{
						if(ji==a[doi])
						{
							doi--;
							ji=0;
						}
						else
						{
							aa=a[doi];
							jii=ji;
							ji-=min(aa,jii);
							a[doi]-=min(aa,jii);
							if(ji>0)
							{
								doi--;
							}
						}
					}
					else
					{
						if(ji==a[doi])
						{
							ans+=ji;
							doi--;
							ji=0;
						}
						else
						{
							aa=a[doi];
							jii=ji;
							ans+=min(aa,jii);
							ji-=min(aa,jii);
							a[doi]-=min(aa,jii);
							if(ji>0)
							{
								doi--;
							}	
						}
					}
				}
			}
		}
		if(fl)
		{
			if(fii)
			{
				doi--;
			}
			else
			{
				upi++;
			}
		}
		if(ch[upi]!=ch[doi]&&ji==0&&upi<doi)
		{
			if(a[upi]>a[doi])
			{
				ans+=a[doi];
				ji+=a[upi]-a[doi];
				fii=0;
				doi--;
			}
			else if(a[upi]<a[doi])
			{
				ans+=a[upi];
				ji+=a[doi]-a[upi];
				fii=1;
				upi++;
			}
			else
			{
				ans+=a[upi];
				upi++;
				doi--;
			}
		}
		if(ch[upi]==ch[doi]&&ji==0&&upi<doi)
		{
			if(a[upi]>a[doi])
			{
				a[upi]-=a[doi];
				doi--;
			}
			else if(a[upi]<a[doi])
			{
				a[doi]-=a[upi];
				upi++;
			}
			else
			{
				upi++;
				doi--;
			}
		}
	}
	cout<<ans;
	return 0;
}
