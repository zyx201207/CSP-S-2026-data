int main(){
#ifdef online
	freopen("subway.in","r",stdin);
	freopen("subway.out","w",stdout);
#endif
	ios::sync_with_stdio(0);cin.tie(0);
	cin>>n>>n>>m>>d>>q;
	for(int i=1;i<=m;i++) cin>>w[i];
	for(int i=1;i<=n;i++){
		int k;cin>>k;
		for(int j=1;j<=k;j++){
			int a,t;cin>>a>>t;
			sub[i].push_back({a,t});node[a].push_back({i,t});
		}
	}
	//此处建图
	for(int i=1;i<=m;i++){//枚举每个方点 
		for(st v:node[i]){//两两组合 
			for(st vv:node[i]){
				if(v==vv)continue;
				if(!dian[v.v][vv.v]) dian[v.v][vv.v]=v.w+vv.w;
				else dian[v.v][vv.v]=min(dian[v.v][vv.v],v.w+vv.w);
			}
		}
	} for(int i=1;i<=n;i++){
		for(int j=1;j<=n;j++){
			if(dian[i][j]){
				tu[i].push_back({j,dian[i][j]}),tu[j].push_back({i,dian[i][j]});
//				cout<<"rp+++ "<<i<<' '<<j<<' '<<dian[i][j]<<endl;
			}
		}
	}
	//O(n^3) 的dijkstra 
	
	for(int k=1;k<=n;k++){
		for(int i=1;i<=n;i++) b[i]=0,dis[k][i]=1e18;dis[k][k]=0;
		for(int i=1;i<=n;i++){
			ll mx=LLONG_MAX,idx=0;
			for(int j=1;j<=n;j++){
				if(!b[j]&&dis[k][j]!=1e18){
					if(dis[k][j]<mx) mx=dis[k][j],idx=j;
				}
			}b[idx]=1;
			for(st v:tu[idx]){
				if(dis[k][idx]+v.w<dis[k][v.v]){
					dis[k][v.v]=dis[k][idx]+v.w;
//					cout<<k<<' '<<idx<<' '<<dis[k][v.v]<<endl;
				}
			}
		}
	}//cout<<"rp++++ "<<dis[1][3]<<endl; 
	while(q--){
		int x,y;cin>>x>>y;ll ans=LLONG_MAX;
		for(st v:node[x]){
			for(st vv:node[y]){
				ans=min(ans,dis[v.v][vv.v]+v.w+vv.w);//圆点距离+两个圆点的进站距离 
			}
		}cout<<ans+w[x]+w[y]<<endl;
	}
	
	return 0;
}
