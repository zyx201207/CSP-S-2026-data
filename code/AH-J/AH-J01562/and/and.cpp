long long n,m,now,maxn,ans;
int a[200005];
long long work(int m,int k){
	if(k==n)return a[k];
	if(m==0)return a[k];
	for(int i=k+1;i<=n;i++){
		return a[i]&work(m-1,i+1);
	}
}
