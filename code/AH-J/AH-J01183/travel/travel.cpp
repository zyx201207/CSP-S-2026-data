#include <iostream>
using namespace std;
int main()
{
	freopen("travel.in","r",stdin);
	freopen("travel.out","w",stdout);
	string c1,s1,c2,s2;
	cin >> c1 >> s1 >> c2 >> s2;
	if(c1!=c2)
	{
		cout << "0000";
		return 0;
	}
	if((s1[0]+s1[1])!=(s2[0]+s2[1]))
	{
		cout << "1000";
		return 0;
	}
	if((s1[2]<='C' && s2[2]>'C') || (s1[2]>'C' && s2[2]<='C'))
	{
		cout << "1100";
		return 0;
	}
	char x1=s1[2],x2=s2[2];
	if(x1>x2)
	{
		swap(x1,x2);
	}
	if(x1=='A' && x2=='C')
	{
		cout << "1110";
		return 0;
	}
	cout << "1111";
	return 0;
}









































































































































































































































