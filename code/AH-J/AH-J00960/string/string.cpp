#include<bits/stdc++.h>
using namespace std;
long long a[200005];
char c[200005];
int main(){
    freopen("string.in","r",stdin);
    freopen("string.out","w",stdout);

    int n;
    scanf("%d",&n);
    for(int i=1;i<=n;i++){
        scanf("%lld",&a[i]);
        cin>>c[i];
    }
    int l=1,r=n;
    long long prel=0ll,lenl=a[1],prer=0ll,lenr=a[n];
    long long ans=0;
    while(l+1<r){
        if(prel!=0){
            if(c[l-1]==c[r]){
                if(lenr>=prel){
                    lenr-=prel;
                    prel=0;
                }else{
                    prel-=lenr;
                    lenr=0;
                }
            }else{
                if(lenr>=prel){
                    ans+=prel;
                    lenr-=prel;
                    prel=0;
                }else{
                    ans+=lenr;
                    prel-=lenr;
                    lenr=0;
                }
            }
        }
        if(prer!=0){
            if(c[r+1]==c[l]){
                if(lenl>=prer){
                    lenl-=prer;
                    prer=0;
                }else{
                    prer-=lenl;
                    lenl=0;
                }
            }else{
                if(lenl>=prer){
                    ans+=prer;
                    lenl-=prer;
                    prer=0;
                }else{
                    ans+=lenl;
                    prer-=lenl;
                    lenl=0;
                }
            }
        }
        if(lenl==0){
            l++;
            prel=lenl;
            lenl=a[l];
            continue;
        }
        if(lenr==0){
            r--;
            prer=lenr;
            lenr=a[r];
            continue;
        }
        if(lenl>lenr){
            if(c[l]!=c[r]){
                ans+=lenr;
            }
            lenl-=lenr;
            r--;
            lenr=a[r];
        }else if(lenl<lenr){
            if(c[l]!=c[r]){
                ans+=lenl;
            }
            lenr-=lenl;
            l++;
            lenl=a[l];
        }else{
            if(c[l]!=c[r]){
                ans+=lenl;
            }
            lenl=0;
            lenr=0;
            l++;
            lenl=a[l];
            r--;
            lenr=a[r];
        }
    }
    if(l+1==r){
        if(prel!=0){
            if(lenr>prel){
                lenr-=prel;
                if(c[l-1]!=c[r]){
                    ans+=prel;
                }
                if(lenr>lenl){
                    lenr-=lenl;
                    if(c[l]!=c[r]){
                        ans+=lenl;
                    }
                }else{
                    lenl-=lenr;
                    if(c[l]!=c[r]){
                        ans+=lenr;
                    }
                }
            }else{
                prel-=lenr;
                if(c[l-1]==c[r]){
                    ans+=lenr;
                }
                if(lenl>prel){
                    if(c[l-1]!=c[l]){
                        ans+=prel;
                    }
                }else{
                    if(c[l-1]!=c[l]){
                        ans+=lenl;
                    }
                }
            }
        }else{
            if(lenl>prer){
                lenl-=prer;
                if(c[r+1]!=c[l]){
                    ans+=prer;
                }
                if(lenl>lenr){
                    lenl-=lenr;
                    if(c[r]!=c[l]){
                        ans+=lenr;
                    }
                }else{
                    lenr-=lenl;
                    if(c[r]!=c[l]){
                        ans+=lenl;
                    }
                }
            }else{
                prer-=lenl;
                if(c[r+1]==c[l]){
                    ans+=lenl;
                }
                if(lenr>prer){
                    if(c[r+1]!=c[r]){
                        ans+=prer;
                    }
                }else{
                    if(c[r+1]!=c[r]){
                        ans+=lenr;
                    }
                }
            }
        }
    }
    cout<<ans;
    return 0;
}
