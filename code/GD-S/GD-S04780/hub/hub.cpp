#include<bits/stdc++.h>
#define ll long long
using namespace std;
const ll N=2e6+10;
ll c,t,n,d,x[N];
int main(){
	freopen("hub.in","r",stdin);
	freopen("hub.out","w",stdout);
	scanf("%lld%lld",&c,&t);
	while(t--){
		scanf("%lldlld",&n,&d);
		for(ll i=1;i<=n;i++)
			scanf("%lld",x+i);
		
	}
	fclose(stdin);
	fclose(stdout);
	return 0;
}

