#include<bits/stdc++.h>
#define int long long
using namespace std;
namespace Fast{
	inline int fr(){
		int x = 0,f = 1;
		char c = getchar();
		while (c < '0' || c > '9'){
			if (c == '-') f = 0;
			c = getchar();
		}
		while (c >= '0' && c <= '9'){
			x = (x << 1) + (x << 3) + (c ^ 48);
			c = getchar();
		}
		return (f ? x : -x);
	}
	char putstk[1005];
	void fw(int x){
		if (x == 0) return putchar('0'),void();
		if (x < 0) x = -x,putchar('-');
		int tp = 0;
		while (x) putstk[++tp] = ((x % 10) ^ 48),x /= 10;
		while (tp) putchar(putstk[tp--]);
	}
}

using namespace Fast;
const int MAXN = 5e5 + 5;
int n,k,a[MAXN];
signed main(){
	freopen("crystal.in","r",stdin);
	freopen("crystal.out","w",stdout);
	n = fr(),k = fr();
	for (int i = 1;i <= n;i++) a[i] = fr();
	sort(a + 1,a + n + 1);
	int l = 1,ans = 1,sum = 0;
	for (int i = 2;i <= n;i++){
		sum += (i - l) * (a[i] - a[i - 1]);
		while (l < i && sum > k){
			sum -= (a[i] - a[l]);
			l++;
		}
		ans = max(ans,i - l + 1);
	}
	fw(ans);
	return 0;
}
