#include<bits/stdc++.h>
#define ll unsigned long long
using namespace std;
int c,n,m,d,q;
struct subway
{
	int k;
	vector<int> a;
	vector<ll> t;
}s[501];
ll w[10001];
ll t[10001][10001];//记录i到j的时间 
void solve()
{
	memset(t,0x3f,sizeof(t));
	for(int i=1;i<=m;i++) t[i][i]=0;
	for(int i=1;i<=n;i++)
	{
		for(int j=0;j<s[i].k;j++)
		{
			for(int k=0;k<s[i].k;k++)
			{
				int x=s[i].a[j],y=s[i].a[k];
				t[x][y]=min(t[x][y],s[i].t[j]+s[i].t[k]); 
			}
		}
	}
	for(int i=1;i<=m;i++)
	{
		for(int j=1;j<=m;j++)
		{
			for(int k=1;k<=m;k++)
			{
				t[i][j]=min(t[i][j],t[i][k]+t[j][k]);
			}
		}
	}
	for(int i=1;i<=m;i++)
		for(int j=1;j<=m;j++)
			t[i][j]=t[i][j]+w[i]+w[j];
}
int main()
{
	cin.tie(0);
	cout.tie(0);
	freopen("subway.in","r",stdin);
	freopen("subway.out","w",stdout);
	cin>>c>>n>>m>>d>>q;
	for(int i=1;i<=m;i++) cin>>w[i];
	for(int i=1;i<=n;i++) 
	{
		cin>>s[i].k;
		for(int j=1;j<=s[i].k;j++)
		{
			int x;
			ll y;
			cin>>x>>y;
			s[i].a.push_back(x);
			s[i].t.push_back(y);
		}
	}
	solve();
	while(q--)
	{
		int x,y;
		cin>>x>>y;
		cout<<t[x][y]<<'\n';
	}
	return 0;
}
