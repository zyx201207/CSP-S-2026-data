#include<bits/stdc++.h>
using namespace std;
long long c,n,m,d,q;
long long s1,s2,minn;
long long a[999999],b[999999];//a表示出入站的时间，b表示每条线站点数 
struct S{
	long long t;//出站时间 
	long long zhan;//站台编号 
	bool ss=0;
}s[999][999];
bool cmp(S x,S y){
	return x.zhan<y.zhan;
}
int B(int x,int y){
	for(int i=1;i<=b[y];i++){
		if(s[y][i].zhan == x ) return i;
	}
	return 0;
}
void A(int x ,int y ,int z ){//x 当前站台号 y所用的时间 z当前线路号 
	if( x == s2 ){
		y = y + a[x] +s[z][B(x,z)].t ;
		if( y < minn ){
			minn=y;
		}
		return;
	}
	for(int i = 1 ; i <= b[z] ; i++ ){
		if( s[z][i].ss == 0 ){
			s[z][i].ss = 1 ;
			A( s[z][i].zhan , y , z );
			s[z][i].ss = 0 ;
		}
		for( int j = 1 ; j <= n ; j++ ){//转线 
			if(j==z) continue;
			if(s[j][B(x,j)].zhan ==x&&s[j][B(x,j)].ss ==0){
				s[j][B(x,j)].ss =1;
				A( x , y + s[z][B(x,z)].t + s[j][B(x,j)].t , j );
				s[j][B(x,j)].ss = 0 ;
			}
		}
	}
	return;
}

