#define ll long long
#define maxn 500010

ll n,k,ans,tot,l=1,r=1,a[maxn];

int main(){
	ios::sync_with_stdio(0);
	cin.tie(0); cout.tie(0);
	freopen("crystal.in","r",stdin);
	freopen("crystal.out","w",stdout);
	cin>>n>>k;
	for(int i=1;i<=n;i++) cin>>a[i];
	sort(a+1,a+1+n); 
	while(1){
		while(tot+(r-l)*(a[r]-a[r-1])>k) tot-=a[r-1]-a[l++]; 
		tot+=(r-l)*(a[r]-a[r-1]);
		ans=max(ans,r-l+1);
		r++;
		if(r>n) break;
	}
	cout<<ans;
	return 0;
}
