using namespace std;
#define int signed long long
const int N=5e5+10;
int n,m,a[N],s[N+1];
bool judge(int x)
{
	int ans=(x-1)*a[x]-s[x];
	if(abs(ans)<=m)return 1;
	return 0;
}
signed main()
{
	freopen("crystal.in","r",stdin);
	freopen("crystal.out","w",stdout);
	cin>>n>>m;
	for(int i=1;i<=n;i++)cin>>a[i];
	sort(a+1,a+1+n);
	for(int i=1;i<=n;i++)s[i]=s[i-1]+a[i]; 
	int l=1,r=n;
	while(l<r)
	{
		int mid=(l+r+1)/2;
		if(judge(mid))l=mid;
		else r=mid-1;
	}
	cout<<l;
   return 0;
}
