#include<bits/stdc++.h>
#define ll long long
using namespace std;
inline ll read(){
ll x=0; int f=1;
char c=getchar();
while(c<'0'||c>'9'){
if(c=='-') f=-1;
c=getchar();
}
while(c>='0'&&c<='9'){
x=x*10+c-'0';
c=getchar();
}
return x*f;
}
const int N=505;
const int M=500005;
const ll inf=1e18;
int c,n,m,d,q,w[M];
ll f[N][N];
vector<pair<int,int>>v[M];
signed main(){
freopen("subway.in","r",stdin);
freopen("subway.out","w",stdout);
c=read(),n=read(),m=read(),d=read(),q=read();
for(int i=1;i<=m;i++) w[i]=read(),v[i].push_back({0,0});
for(int i=1;i<=n;i++){
int k=read();
for(int j=1;j<=k;j++){
int x=read(),w=read();
v[x].push_back({i,w});
}
for(int j=1;j<=n;j++) f[i][j]=1e18; f[i][i]=0;
}
for(int i=1;i<=m;i++){
int len=v[i].size()-1;
for(int j=1;j<=len;j++){
int x=v[i][j].first;
ll w1=v[i][j].second;
for(int k=j+1;k<=len;k++){
int y=v[i][k].first;
ll w2=v[i][k].second;
f[x][y]=f[y][x]=min(f[x][y],w1+w2);
}
}
}
for(int k=1;k<=n;k++){
for(int i=1;i<=n;i++){
for(int j=1;j<=n;j++){
f[i][j]=min(f[i][j],f[i][k]+f[k][j]);
}
}
}
while(q--){
int x=read(),y=read();
int len1=v[x].size()-1,len2=v[y].size()-1;
ll ans=inf;
for(int i=1;i<=len1;i++){
int t1=v[x][i].first,w1=v[x][i].second;
for(int j=1;j<=len2;j++){
ans=min(ans,f[t1][v[y][j].first]+w1+v[y][j].second);
}
}
cout<<ans+w[x]+w[y]<<'\n';
}
return 0;
}
