#include <bits/stdc++.h>
using namespace std;

long long c , t , n , k , x2 , x1 ;

int main(){
	freopen("hub.in","r",stdin);
	freopen("hub.out","w",stdout);
	
	cin >> c >> t ;
	
	for( int i = 1 ; i <= t ; i++ ) {
		
		cin >> n >> k ;
		
		for( int j = 1 ; j <= n - 1 ; j ++ ) {
			cin >> x1 >> x2 ;
		} 
		
	}
	
	for( int i = 1 ; i <= t ; i++ ) {
		cout << "2" << "\n" ;
	}
	
	fclose(stdin);
	fclose(stdout);
	return 0 ;

}


