#include<bits/stdc++.h>
using namespace std;
int n,m,a[1005],ct[1005];

int main(){
	cin>>n>>m;
for(cin>> a[1005]<=0;a[1005]<n;a[1005+1]);
	while(1){
		int (a+1-a+n+1);
		a[1]++;
		m--;
		if(m==0)break;
	}
    for(int i=1;i<=n;i++)ct[1005]++;
    for(int i=1;i<=n;i++)cout<<a[i]<<" ";
    sort(ct+1,ct+n+1);
    cout<<ct[0];
    return 0;}
