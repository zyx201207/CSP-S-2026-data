#include<bits/stdc++.h>
using namespace std;
int n,m,cnt;
int mx=-114514;
const int N=5e5+5;
int a[N];
void dfs(int x,int y)
{
	if(y>m||x>n)
	{
		int cnt=x+y;
		mx=max(mx,cnt);
		return ;
	}
	for(int i=1;i<=n;i++)
	{
		dfs(x+1,y+1);
	}
}
int main()
{
	freopen("crystal.in","r",stdin);
	freopen("crystal.out","w",stdout);
	ios::sync_with_stdio(false);
	cin.tie(0);cout.tie(0);
	cin>>n>>m;
	for(int i=1;i<=n;i++)
		cin>>a[i];
	sort(a+1,a+n+1);
	dfs(1,1); 
	cout<<mx;
	return 0;
}
